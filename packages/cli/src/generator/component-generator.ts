/**
 * @module component-generator
 * Generates Astro component files from CMS schema introspection.
 * Each collection in the schema produces a ready-to-use `.astro` component
 * with typed props, semantic HTML, and Visual Bridge compatibility attributes.
 */

import type { SchemaDefinition, SchemaCollection, SchemaField, FieldType } from '@intijs/core/adapters';

// ============================================
// Public Types
// ============================================

/** Options for the Astro component generator */
export interface ComponentGeneratorOptions {
    /** Directory where generated components will be written */
    outputDir: string;
    /** Whether to overwrite existing component files (default: false) */
    overwrite?: boolean;
    /** Generate with or without Tailwind/UnoCSS utility classes (default: 'styled') */
    style?: 'minimal' | 'styled';
    /** Include a typed Astro Props interface in the frontmatter (default: true) */
    includeProps?: boolean;
    /** Include JSDoc comments in the generated component (default: true) */
    includeJsDoc?: boolean;
}

/** Represents a single generated component and its metadata */
export interface GeneratedComponent {
    /** PascalCase component name derived from the collection */
    name: string;
    /** Output filename, e.g. `BlogPost.astro` */
    filename: string;
    /** Full resolved path on disk */
    path: string;
    /** Complete file content ready to be written */
    content: string;
    /** Whether this component did not previously exist on disk */
    isNew: boolean;
}

// ============================================
// Title-like field heuristics
// ============================================

/** Field names that should be rendered as headings rather than paragraphs */
const TITLE_FIELD_PATTERNS = [
    'title', 'name', 'heading', 'headline', 'subject', 'label',
];

/**
 * Determine whether a field name looks like a "title" field.
 * Used to decide between `<h2>` and `<p>` for plain string fields.
 */
function isTitleField(fieldName: string): boolean {
    const lower = fieldName.toLowerCase();
    return TITLE_FIELD_PATTERNS.some(p => lower === p || lower.endsWith(`_${p}`) || lower.endsWith(`${p}`));
}

// ============================================
// Kebab-case helper
// ============================================

/**
 * Convert a PascalCase or camelCase string to kebab-case.
 * e.g. `BlogPost` → `blog-post`
 */
function toKebabCase(str: string): string {
    return str
        .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
        .replace(/([A-Z])([A-Z][a-z])/g, '$1-$2')
        .toLowerCase();
}

// ============================================
// Component Content Generation
// ============================================

/**
 * Generate the complete `.astro` file content for a single collection.
 */
function generateComponentContent(
    collection: SchemaCollection,
    options: Required<Pick<ComponentGeneratorOptions, 'style' | 'includeProps' | 'includeJsDoc'>>,
): string {
    const { name, fields } = collection;
    const kebab = toKebabCase(name);
    const styled = options.style === 'styled';

    // --- Frontmatter ---
    const frontmatterLines: string[] = ['---'];

    if (options.includeJsDoc) {
        frontmatterLines.push(
            '/**',
            ` * ${name} Block Component`,
            ` * Auto-generated by Inti CLI - Customize as needed`,
            ` * @see https://github.com/intijs/inti/blob/main/apps/docs/src/content/docs/registry/components.mdx`,
            ' */',
        );
    }

    frontmatterLines.push(`import type { ${name} } from '../../lib/inti/inti.types';`);
    frontmatterLines.push('');

    if (options.includeProps) {
        frontmatterLines.push('interface Props {');
        if (options.includeJsDoc) frontmatterLines.push('  /** Block data from CMS */');
        frontmatterLines.push(`  data: ${name};`);
        if (options.includeJsDoc) frontmatterLines.push('  /** Block ID for Visual Bridge */');
        frontmatterLines.push('  blockId?: string;');
        if (options.includeJsDoc) frontmatterLines.push('  /** Document ID in CMS */');
        frontmatterLines.push('  documentId?: string;');
        frontmatterLines.push('}');
        frontmatterLines.push('');
    }

    frontmatterLines.push('const { data, blockId, documentId } = Astro.props;');
    frontmatterLines.push('---');

    // --- Template ---
    const templateLines: string[] = [];

    const sectionClass = styled
        ? `class="inti-block inti-block--${kebab} p-6"`
        : `class="inti-block inti-block--${kebab}"`;

    templateLines.push('');
    templateLines.push(`<section`);
    templateLines.push(`  ${sectionClass}`);
    templateLines.push(`  data-inti-block="${name}"`);
    templateLines.push(`  data-inti-block-id={blockId}`);
    templateLines.push(`  data-inti-document-id={documentId}`);
    templateLines.push(`>`);

    // Render each field
    for (const field of fields) {
        const fieldLines = generateFieldMarkup(field, styled);
        templateLines.push(...fieldLines);
    }

    templateLines.push(`</section>`);

    return [...frontmatterLines, ...templateLines, ''].join('\n');
}

/**
 * Generate the HTML template lines for a single schema field.
 */
function generateFieldMarkup(field: SchemaField, styled: boolean): string[] {
    const { name: f, type, required } = field;
    const lines: string[] = [];
    const indent = '  ';

    // Determine whether the field needs conditional rendering
    const needsConditional = !required;

    /**
     * Wraps content lines in a conditional `{data.field && (...)}` block
     * when the field is optional.
     */
    const wrap = (inner: string[]): string[] => {
        if (!needsConditional) {
            return inner.map(l => `${indent}${l}`);
        }
        const out: string[] = [];
        out.push('');
        out.push(`${indent}{data.${f} && (`);
        inner.forEach(l => out.push(`${indent}${indent}${l}`));
        out.push(`${indent})}`);
        return out;
    };

    switch (type) {
        case 'string':
            if (isTitleField(f)) {
                lines.push(...wrap([
                    styled
                        ? `<h2 class="text-3xl font-bold mb-4">{data.${f}}</h2>`
                        : `<h2>{data.${f}}</h2>`,
                ]));
            } else {
                lines.push(...wrap([
                    styled
                        ? `<p class="mb-2">{data.${f}}</p>`
                        : `<p>{data.${f}}</p>`,
                ]));
            }
            break;

        case 'text':
        case 'richtext':
            lines.push(...wrap([
                styled
                    ? `<div class="prose max-w-none" set:html={data.${f}} />`
                    : `<div set:html={data.${f}} />`,
            ]));
            break;

        case 'media':
            lines.push(...wrap([
                styled ? `<figure class="mb-6">` : `<figure>`,
                `  <img`,
                `    src={data.${f}.url}`,
                `    alt={data.${f}.alt || ''}`,
                `    loading="lazy"`,
                styled
                    ? `    class="w-full rounded-lg object-cover"`
                    : `    `,
                `  />`,
                `</figure>`,
            ]));
            break;

        case 'number':
            lines.push(...wrap([
                styled
                    ? `<span class="font-mono">{data.${f}}</span>`
                    : `<span>{data.${f}}</span>`,
            ]));
            break;

        case 'boolean':
            lines.push('');
            lines.push(`${indent}{data.${f} && (`);
            lines.push(`${indent}${indent}${styled
                ? `<span class="inline-block px-2 py-1 text-sm bg-green-100 text-green-800 rounded">${f}</span>`
                : `<span>${f}</span>`
            }`);
            lines.push(`${indent})}`);
            break;

        case 'date':
        case 'datetime':
            lines.push(...wrap([
                `<time`,
                `  datetime={new Date(data.${f}).toISOString()}`,
                styled
                    ? `  class="text-sm text-gray-500 mb-4 block"`
                    : `  `,
                `>`,
                `  {new Date(data.${f}).toLocaleDateString()}`,
                `</time>`,
            ]));
            break;

        case 'relation':
            lines.push('');
            lines.push(`${indent}<!-- TODO: Render related "${f}" data (relation) -->`);
            lines.push(`${indent}<slot name="${f}" />`);
            break;

        case 'json':
            lines.push(...wrap([
                `<pre>{JSON.stringify(data.${f}, null, 2)}</pre>`,
            ]));
            break;

        case 'blocks':
        case 'component':
            lines.push('');
            lines.push(`${indent}<!-- TODO: Render nested "${f}" blocks/components -->`);
            lines.push(`${indent}<slot name="${f}" />`);
            break;

        default:
            lines.push(...wrap([
                `<span>{data.${f}}</span>`,
            ]));
            break;
    }

    return lines;
}

// ============================================
// Public API
// ============================================

/**
 * Generate Astro component files for every collection in the schema.
 *
 * @param schema - The introspected CMS schema definition
 * @param options - Generation options (output dir, style, overwrite, etc.)
 * @returns An array of {@link GeneratedComponent} objects ready for writing to disk
 */
export function generateAstroComponents(
    schema: SchemaDefinition,
    options: ComponentGeneratorOptions,
): GeneratedComponent[] {
    const {
        outputDir,
        overwrite = false,
        style = 'styled',
        includeProps = true,
        includeJsDoc = true,
    } = options;

    const resolvedOpts = { style, includeProps, includeJsDoc } as const;

    return schema.collections.map(collection => {
        const filename = `${collection.name}.astro`;
        const fullPath = `${outputDir}/${filename}`;

        return {
            name: collection.name,
            filename,
            path: fullPath,
            content: generateComponentContent(collection, resolvedOpts),
            // `isNew` is determined at write-time by the command; default true here
            isNew: true,
        };
    });
}
