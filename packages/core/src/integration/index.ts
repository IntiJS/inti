/**
 * Inti - Astro Integration
 * 
 * The visual editing layer for headless WordPress on Astro. Content stays in the CMS;
 * editors change it by double-clicking on the rendered page.
 * 
 * @module @intijs/core/integration
 * @example
 * ```ts
 * // astro.config.mjs
 * import { defineConfig } from 'astro/config';
 * import inti from '@intijs/core';
 * 
 * export default defineConfig({
 *   integrations: [inti()]
 * });
 * ```
 */

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

import type { AstroIntegration, ViteUserConfig } from 'astro';

/**
 * An `injectRoute` entrypoint Astro can read even when the path contains `#`.
 *
 * Installed from git, pnpm stores the package in a folder with `#` in its
 * name (`@intijs+core@git+…#<commit>&path…`). Astro turns the entrypoint into
 * a path relative to the root and then does `new URL(path, root)`: the `#` is
 * taken as a fragment, the path gets cut and the build dies with ENOENT
 * (seen with `pnpm add git+file://…#<commit>&path:/packages/core`).
 *
 * In that case a one-line file is written to `<root>/.astro/inti/` that
 * re-exports the route from the package (`export * from '@intijs/core/api/…'`):
 * its own path has no `#`, and Vite resolves what it imports like any other
 * import. Without `#` (npm, local link) the specifier is used as is, as
 * always.
 */
function routeEntry(specifier: string, root: URL): string {
  let resolved: string;
  try {
    resolved = fileURLToPath(import.meta.resolve(specifier));
  } catch {
    return specifier;
  }
  if (!resolved.includes('#')) return specifier;

  const folder = new URL('./.astro/inti/', root);
  mkdirSync(folder, { recursive: true });
  const name = specifier.split('/').pop() ?? 'route.ts';
  const target = new URL(name, folder);
  // A page cannot be re-exported: it is wrapped in another page that renders it
  if (name.endsWith('.astro')) {
    writeFileSync(
      target,
      `---\n// Generated by @intijs/core (integration/index.ts, routeEntry): do not edit.\n` +
        `import Page from '${specifier}';\nexport const prerender = false;\nexport const partial = true;\n---\n<Page />\n`
    );
    return fileURLToPath(target);
  }
  const original = readFileSync(resolved, 'utf8');
  const prerender = original.match(/^export const prerender\s*=\s*(true|false);?/m)?.[0] ?? '';
  writeFileSync(
    target,
    `// Generated by @intijs/core (integration/index.ts, routeEntry): do not edit.\n` +
      `export * from '${specifier}';\n` +
      (prerender ? `${prerender}\n` : '')
  );
  return fileURLToPath(target);
}

/**
 * Options for the Inti Astro integration
 */
export interface IntiIntegrationOptions {
  /**
   * @deprecated No effect. It never disabled the editor: it only controlled two
   * scripts that were injected into every page and did nothing. To turn
   * the editor off use `<VisualBridgeAuto enabled={false} />`.
   */
  visualBridge?: boolean;
  /** Enable real-time collaboration features (default: false) */
  realtime?: boolean;
  /** Path to Inti config file (default: './inti.config.ts') */
  configPath?: string;
  /** Custom Vite config modifications */
  vite?: ViteUserConfig;
}

/**
 * Creates the Inti Astro integration
 * 
 * This integration provides:
 * - Visual Bridge Dev Toolbar for in-site editing
 * - Real-time collaboration WebSocket server
 * - Automatic adapter detection and configuration
 * 
 * @param options - Integration options
 * @returns AstroIntegration instance
 * 
 * @example
 * ```ts
 * // Minimal setup
 * export default defineConfig({
 *   integrations: [inti()]
 * });
 * 
 * // With options
 * export default defineConfig({
 *   integrations: [
 *     inti({
 *       realtime: true,
 *       configPath: './config/inti.config.ts'
 *     })
 *   ]
 * });
 * ```
 */
export default function inti(options: IntiIntegrationOptions = {}): AstroIntegration {
  const {
    realtime = false,
    configPath = './inti.config.ts',
  } = options;

  return {
    name: 'inti',
    hooks: {
      /**
       * Hook: astro:config:setup
       * Called when the Astro config is being set up
       */
      'astro:config:setup': async ({
        config,
        injectRoute,
        updateConfig,
        logger,
        command,
      }) => {
        logger.info('Setting up Inti integration...');

        // Two scripts used to be injected here into ALL pages: a "state
        // manager shared between islands" that nothing read and a
        // console.log for localhost. They reached every visitor in
        // production —they were all the JS of a page without the editor— and
        // did nothing. The editor loads its own code only when it renders.
        // No app is registered in Astro's dev toolbar. One used to be
        // registered with `entrypoint: './visual-bridge/dev-toolbar.js'`,
        // a file that does not exist: in `astro dev` Vite drew its error
        // overlay over the page and swallowed every click, so inline
        // editing became unusable. The editor has its own UI.

        // 3. Routes inline editing needs with any CMS
        injectRoute({
          pattern: '/api/inti/search',
          entrypoint: routeEntry('@intijs/core/api/search.ts', config.root)
        });

        injectRoute({
          pattern: '/api/inti/sync',
          entrypoint: routeEntry('@intijs/core/api/sync.ts', config.root)
        });

        injectRoute({
          pattern: '/api/inti/generate',
          entrypoint: routeEntry('@intijs/core/api/generate.ts', config.root)
        });

        injectRoute({
          pattern: '/api/inti/preview',
          entrypoint: routeEntry('@intijs/core/api/preview.astro', config.root)
        });

        injectRoute({
          pattern: '/api/inti/preferences',
          entrypoint: routeEntry('@intijs/core/api/preferences.ts', config.root)
        });

        // 4. Update Vite config for optimal Inti support
        const noExternal: (string | RegExp)[] = ['@intijs/core'];
        const existingNoExternal = options.vite?.ssr?.noExternal;
        if (existingNoExternal) {
          if (Array.isArray(existingNoExternal)) {
            noExternal.push(...existingNoExternal.filter((item): item is string | RegExp => 
              typeof item === 'string' || item instanceof RegExp
            ));
          } else if (typeof existingNoExternal === 'string' || existingNoExternal instanceof RegExp) {
            noExternal.push(existingNoExternal);
          }
        }

        updateConfig({
          vite: {
            ...options.vite,
            ssr: {
              ...(options.vite?.ssr || {}),
              noExternal,
              external: [
                ...((options.vite?.ssr?.external as string[]) || [])
              ]
            },
            resolve: {
              ...(options.vite?.resolve || {}),
              alias: {
                ...(options.vite?.resolve?.alias || {}),
                'inti.config': configPath,
              },
            },
            define: {
              ...(options.vite?.define || {}),
              __INTI_CONFIG_PATH__: JSON.stringify(configPath),
              __INTI_REALTIME__: JSON.stringify(realtime),
            },
          },
        });

        logger.info('Inti integration setup complete');
      },

      /**
       * Hook: astro:config:done
       * Called after all integrations have run astro:config:setup
       */
      'astro:config:done': async ({ config, logger }) => {
        logger.debug('Inti config resolved');

        // Inline editing writes via astro:actions, and actions only
        // exist if there is an Astro adapter: without one, the
        // /_actions/* endpoint is never generated and every save fails
        // with a 404 that explains nothing. The warning is given here, at
        // startup, instead of letting people discover it on the first double click.
        if (!config.adapter) {
          logger.warn(
            'No Astro adapter configured — astro:actions is unavailable, so inline editing ' +
            'cannot save. Install one (e.g. `npx astro add node`) to enable write-back. ' +
            'Reading content works without it.'
          );
        }
      },

      /**
       * Hook: astro:server:setup
       * Called when the dev server is being set up
       */
      'astro:server:setup': async ({ server, logger }) => {
        // Relay of edits between tabs/editors in dev.
        // Uses the WebSocket of Vite's own dev server (custom events):
        // the inline editor emits 'inti:content-updated' after every save
        // and here it is rebroadcast to all connected clients.
        server.ws.on('inti:content-updated', (data: unknown) => {
          server.ws.send('inti:content-updated', data);
        });
        logger.info('Inti dev broadcast ready (inline edits sync across tabs)');

        if (realtime) {
          // Heavy collaboration (cursors, presence, conflicts) uses the
          // RealtimeClient against a dedicated WebSocket endpoint in
          // production; the broadcast above covers dev mode.
          logger.info('Inti realtime: production collaboration requires a dedicated WS endpoint (see realtime/)');
        }
      },

      /**
       * Hook: astro:build:start
       * Called at the beginning of the build process
       */
      'astro:build:start': async ({ logger }) => {
        logger.info('Inti: Starting build with Content Bridge...');
      },

      /**
       * Hook: astro:build:done
       * Called after the build is complete
       */
      'astro:build:done': async ({ logger, pages }) => {
        const pageCount = Array.isArray(pages) ? pages.length : 0;
        logger.info(`Inti: Build complete. ${pageCount} pages generated.`);
      },
    },
  };
}

