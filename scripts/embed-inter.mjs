#!/usr/bin/env node
/**
 * Generates packages/infographic/src/fonts/inter.ts: the Inter files the built-in themes use,
 * embedded as base64, from the installed @fontsource/inter.
 *
 * Why embedded: a font found on disk at run time depends on the platform shipping the file.
 * Vercel's and Netlify's file tracers only ship files the code names with a literal path, and
 * a Worker has no disk at all, so the renderer fell back to fetching the font from Google on
 * every cold start, or failed with no network. A module is shipped by every bundler.
 *
 * Usage: node scripts/embed-inter.mjs   (after npm install)
 */

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(join(ROOT, 'packages/infographic/package.json'));
const version = JSON.parse(readFileSync(require.resolve('@fontsource/inter/package.json'), 'utf8')).version;

const WEIGHTS = [400, 600, 800];
const SUBSETS = ['latin', 'latin-ext'];

const entries = [];
for (const weight of WEIGHTS) {
    for (const subset of SUBSETS) {
        const data = readFileSync(require.resolve(`@fontsource/inter/files/inter-${subset}-${weight}-normal.woff`));
        entries.push(`    '${subset}-${weight}': '${data.toString('base64')}'`);
    }
}

const out = join(ROOT, 'packages/infographic/src/fonts/inter.ts');
mkdirSync(dirname(out), { recursive: true });
writeFileSync(
    out,
    `/**
 * Inter ${WEIGHTS.join(', ')}, Latin and Latin Extended, as WOFF. Generated by
 * scripts/embed-inter.mjs from @fontsource/inter ${version}: do not edit by hand.
 *
 * Inter is copyright The Inter Project Authors and licensed under the SIL Open Font License
 * 1.1, included as packages/infographic/fonts/OFL.txt.
 */

const FILES: Record<string, string> = {
${entries.join(',\n')}
};

export const INTER_WEIGHTS = [${WEIGHTS.join(', ')}] as const;

/** The embedded files for these weights, decoded */
export function interFonts(weights: readonly number[] = INTER_WEIGHTS): { name: 'Inter'; data: Uint8Array; weight: 400 | 600 | 800; style: 'normal' }[] {
    const fonts: { name: 'Inter'; data: Uint8Array; weight: 400 | 600 | 800; style: 'normal' }[] = [];
    for (const weight of weights) {
        for (const subset of ${JSON.stringify(SUBSETS)}) {
            const base64 = FILES[\`\${subset}-\${weight}\`];
            if (!base64) continue;
            const binary = atob(base64);
            const data = new Uint8Array(binary.length);
            for (let i = 0; i < binary.length; i++) data[i] = binary.charCodeAt(i);
            fonts.push({ name: 'Inter', data, weight: weight as 400 | 600 | 800, style: 'normal' });
        }
    }
    return fonts;
}
`
);

const license = readFileSync(join(dirname(require.resolve('@fontsource/inter/package.json')), 'LICENSE'), 'utf8');
mkdirSync(join(ROOT, 'packages/infographic/fonts'), { recursive: true });
writeFileSync(join(ROOT, 'packages/infographic/fonts/OFL.txt'), license);
console.log(`Wrote ${out} (${entries.length} files, @fontsource/inter ${version})`);
